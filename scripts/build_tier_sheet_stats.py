#!/usr/bin/env python3
"""Turn data/tier-sheet-2025-26.json into extension/data/tier-sheet-stats.js.

These are the fallback numbers shown when ESPN data isn't loaded: 2025-26
fantasy points per game in the league's scoring, games played, and market rank.
They're looked up by player name, so they work for an edited list too.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = json.load(open(os.path.join(ROOT, 'data', 'tier-sheet-2025-26.json'), encoding='utf-8'))
js = f'''/* GENERATED by scripts/build_tier_sheet_stats.py from data/tier-sheet-2025-26.json. Do not edit by hand. */
(function (root) {{
  const HDA = (root.HDA = root.HDA || {{}});
  const data = {json.dumps(src, ensure_ascii=False)};
  const norm = (n) => (HDA.normalizeName ? HDA.normalizeName(n) : String(n).toLowerCase());
  HDA.TIER_SHEET_STATS = {{
    source: data.source,
    season: data.season,
    byName: new Map(Object.entries(data.players).map(([n, v]) => [norm(n), v])),
  }};
  if (typeof module !== 'undefined' && module.exports) module.exports = HDA;
}})(typeof globalThis !== 'undefined' ? globalThis : this);
'''
open(os.path.join(ROOT, 'extension', 'data', 'tier-sheet-stats.js'), 'w', encoding='utf-8').write(js)
print(len(src['players']), 'players')
